// One-time migration helper: makes the legacy global stylesheet themeable.
// Every literal colour in a declaration becomes var(--<kind>-<id>, <original>),
// so pages without overrides render exactly as before. It also emits a dark
// palette (derived in HSL) scoped to `.dash[data-theme="dark"]`.
//
// Usage (run once, on untokenized files):
//   node scripts/theme-legacy-css.mjs app/app/legacy-dark.css app/globals.css components/model-management.module.css
import { readFileSync, writeFileSync } from "node:fs";

const [darkOut, ...inputs] = process.argv.slice(2);

// Defaults mirror app/globals.css :root so CSS modules without their own :root work.
const rootVars = {
  canvas: "#f7f6ef",
  ink: "#232923",
  green: "#315b48",
  yellow: "#f1db72",
  muted: "#6b726a",
  line: "#e3e5dc",
  white: "#fffefa",
};
for (const m of readFileSync(inputs[0], "utf8").matchAll(
  /--(canvas|ink|green|yellow|muted|line|white):\s*(#[0-9a-f]{3,8})/gi,
))
  rootVars[m[1]] = m[2];

function kindFor(prop) {
  if (
    /^(color|fill|stroke|caret-color|text-decoration-color|accent-color)$/.test(
      prop,
    )
  )
    return "fg";
  if (/^background/.test(prop)) return "bg";
  if (/^(border|outline|box-shadow|text-shadow)/.test(prop)) return "ln";
  return null;
}

const used = new Map(); // name -> {kind, hex}
for (const input of inputs) {
  const css = readFileSync(input, "utf8");
  let prop = null;
  let inRoot = false;
  const out = css.split("\n").map((line) => {
    if (/^:root\s*\{/.test(line)) inRoot = true;
    if (inRoot) {
      if (line.startsWith("}")) inRoot = false;
      return line;
    }
    const decl = line.match(/^\s*([a-z-]+)\s*:/);
    if (decl) prop = decl[1];
    const kind = prop && !prop.startsWith("--") ? kindFor(prop) : null;
    let result = line;
    if (kind) {
      const valueStart = decl ? line.indexOf(":") + 1 : 0;
      const head = line.slice(0, valueStart);
      let value = line.slice(valueStart);
      value = value.replace(
        /var\(--(canvas|ink|green|yellow|muted|line|white)\)/g,
        (_, name) => {
          const id = `${kind}-${name}`;
          used.set(id, { kind, hex: rootVars[name] });
          return `var(--${id}, var(--${name}))`;
        },
      );
      value = value.replace(
        /(?<![\w-])(#[0-9a-fA-F]{6}|#[0-9a-fA-F]{3}|white)\b(?![\w-])/g,
        (match) => {
          const hex = normalizeHex(match === "white" ? "#ffffff" : match);
          const id = `${kind}-${hex.slice(1)}`;
          used.set(id, { kind, hex });
          return `var(--${id}, ${match})`;
        },
      );
      result = head + value;
    }
    if (/[;{}]$/.test(line.trim())) prop = null;
    return result;
  });
  writeFileSync(input, out.join("\n"));
}

function normalizeHex(hex) {
  let h = hex.toLowerCase();
  if (h.length === 4) h = "#" + [...h.slice(1)].map((c) => c + c).join("");
  return h;
}
function hexToHsl(hex) {
  const n = parseInt(hex.slice(1, 7), 16);
  const r = ((n >> 16) & 255) / 255,
    g = ((n >> 8) & 255) / 255,
    b = (n & 255) / 255;
  const max = Math.max(r, g, b),
    min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0,
    s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h =
      max === r
        ? (g - b) / d + (g < b ? 6 : 0)
        : max === g
          ? (b - r) / d + 2
          : (r - g) / d + 4;
    h /= 6;
  }
  return [h, s, l];
}
const hsl = (h, s, l) =>
  `hsl(${Math.round(h * 360)} ${Math.round(s * 100)}% ${Math.round(l * 1000) / 10}%)`;

function dark({ kind, hex }) {
  const [h, s, l] = hexToHsl(hex);
  if (kind === "bg") {
    // Light neutrals become the dashboard's green-tinted dark surfaces.
    if (l > 0.5)
      return s < 0.45
        ? hsl(150 / 360, 0.16, 0.09 + (1 - l) * 0.35)
        : hsl(h, s * 0.5, 0.09 + (1 - l) * 0.35);
    return hsl(h, s, Math.max(l, 0.3));
  }
  if (kind === "fg") {
    if (l < 0.55)
      return hsl(h, Math.min(s, 0.45), Math.min(0.93, 0.95 - l * 0.6));
    return hsl(h, s * 0.5, Math.max(l, 0.9));
  }
  if (l > 0.5) return hsl(150 / 360, 0.14, 0.18 + (1 - l) * 0.25);
  return hsl(h, s, Math.max(l, 0.35));
}

const lines = [...used.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, info]) => `  --${id}: ${dark(info)};`);
writeFileSync(
  darkOut,
  `/* Generated by scripts/theme-legacy-css.mjs from ${inputs.join(", ")}.\n   Dark palette for the legacy studio components inside the dashboard. */\n.dash[data-theme="dark"] {\n${lines.join("\n")}\n}\n`,
);
console.log(`Tokenized ${used.size} colour uses.`);
